package agent

import (
	"context"

	acp "github.com/coder/acp-go-sdk"
)

// The SDK's Client interface includes the v1 client file system and terminal
// methods. Mu does not advertise them, so it answers as for any unknown method.

func (p *Process) ReadTextFile(context.Context, acp.ReadTextFileRequest) (acp.ReadTextFileResponse, error) {
	return acp.ReadTextFileResponse{}, acp.NewMethodNotFound(acp.ClientMethodFsReadTextFile)
}

